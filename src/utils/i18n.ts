export function getLanguageInfo(codeOrName?: string) {
  if (!codeOrName) return { code: 'TA' as SupportedLanguage, label: 'Tamil', native: 'தமிழ்' };
  const upper = codeOrName.trim().toUpperCase();
  const match = LANGUAGES.find(
    (l) => l.code === upper || l.label.toUpperCase() === upper || l.native === codeOrName
  );
  if (match) return match;
  return { code: upper as SupportedLanguage, label: codeOrName, native: codeOrName };
}

